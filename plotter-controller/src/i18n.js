export function getLang() {
  const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('plotter-lang') : null;
  if (saved === 'en' || saved === 'ru' || saved === 'et') return saved;
  // автоопределение по языку браузера
  const nav = typeof navigator !== 'undefined' ? (navigator.language || '').toLowerCase() : '';
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('et')) return 'et';
  return 'en';
}

export function setLang(code) {
  try { localStorage.setItem('plotter-lang', code); } catch (e) { /* ignore */ }
}

// t(key, params?) — перевод с подстановкой {name}
export function makeT(lang) {
  const table = dict[lang] || dict.ru;
  return (key, params) => {
    let s = table[key] ?? dict.ru[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll('{' + k + '}', v);
    return s;
  };
}

export const LangContext = createContext({ lang: 'ru', setLang: () => {}, t: makeT('ru') });
export const useLang = () => useContext(LangContext);
